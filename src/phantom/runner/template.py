"""
Run-file templates (``phantom new <stage>``) and stage descriptions
(``phantom stages <stage>``), both generated from the stage's ``Params`` so
they can never drift from what the stage actually accepts.
"""

from __future__ import annotations

from typing import Any

import tomlkit

from phantom.runner import params as P
from phantom.runner.stage import RunContext, Stage


def toml_value(value: Any) -> str:
    if isinstance(value, dict):
        table = tomlkit.inline_table()
        table.update(value)
        return table.as_string()
    return tomlkit.item(value).as_string()


def _placeholder(tp: Any) -> str:
    choices = P.literal_choices(tp)
    if choices:
        return toml_value(choices[0])
    return '""'


def _field_lines(stage: Stage, ctx: RunContext | None) -> list[tuple[str, str]]:
    """(``key = value`` line, trailing comment) per parameter."""
    hints = P.type_hints(stage.Params)
    dynamic = stage.defaults(ctx) if ctx is not None else {}
    available = stage.choices(ctx) if ctx is not None else {}
    lines = []
    for f in P.fields(stage.Params):
        tp = hints[f.name]
        notes = []
        if f.name in dynamic:
            line = f"{f.name} = {toml_value(dynamic[f.name])}"
        elif not P.has_static_default(f):
            options = available.get(f.name)
            line = f"{f.name} = {toml_value(options[-1]) if options else _placeholder(tp)}"
            notes.append("REQUIRED")
            if options:
                notes.append("available: " + " | ".join(str(o) for o in options))
        elif P.static_default(f) is None:
            # Optional with a config-derived default: shown commented out.
            line = f"# {f.name} = {_placeholder(tp)}"
        else:
            line = f"{f.name} = {toml_value(P.static_default(f))}"
        choices = P.literal_choices(tp)
        if choices:
            notes.append(" | ".join(str(c) for c in choices))
        if P.is_grid(f):
            notes.append("a list runs one job per value")
        if P.help_text(f):
            notes.append(P.help_text(f))
        lines.append((line, "; ".join(notes)))
    return lines


def render_template(stage: Stage, ctx: RunContext | None = None) -> str:
    out = [
        f"# Generated by: phantom new {stage.name}",
        f"# {stage.summary}",
        "# Fill in REQUIRED values, then: phantom validate <this file> && phantom run <this file>",
        "",
        "[run]",
        f'name = "{stage.name.replace(".", "_")}"',
        "",
        "[[steps]]",
        f'stage = "{stage.name}"',
    ]
    lines = _field_lines(stage, ctx)
    width = max((len(line) for line, _ in lines), default=0)
    for line, note in lines:
        out.append(f"{line.ljust(width)}  # {note}" if note else line)
    return "\n".join(out) + "\n"


def describe_stage(stage: Stage, ctx: RunContext | None = None) -> str:
    hints = P.type_hints(stage.Params)
    dynamic = stage.defaults(ctx) if ctx is not None else {}
    available = stage.choices(ctx) if ctx is not None else {}
    out = [f"{stage.name} -- {stage.summary}", "", "Parameters:"]
    for f in P.fields(stage.Params):
        if f.name in dynamic:
            default = f"default: {toml_value(dynamic[f.name])} (from config.toml)"
        elif P.has_static_default(f):
            d = P.static_default(f)
            default = (
                "default: use the config.toml location"
                if d is None
                else f"default: {toml_value(d)}"
            )
        else:
            default = "REQUIRED"
        grid = ", list = one job per value" if P.is_grid(f) else ""
        out.append(f"  {f.name}: {P.describe(hints[f.name])}{grid}  [{default}]")
        if P.help_text(f):
            out.append(f"      {P.help_text(f)}")
        if f.name in available:
            out.append("      available: " + ", ".join(str(o) for o in available[f.name]))
    return "\n".join(out)


def stages_markdown(stages: list[Stage], ctx: RunContext | None = None) -> str:
    """Every stage and its parameters as one Markdown page (the wiki's Stages page)."""
    out = [
        "# Stages",
        "",
        "Generated by `phantom stages --markdown` from the code -- do not edit by hand.",
        "Parameters marked **grid** accept a list: one job per value.",
        "",
    ]

    def cell(text: str) -> str:
        return text.replace("|", "\\|")

    for stage in sorted(stages, key=lambda s: s.name):
        hints = P.type_hints(stage.Params)
        dynamic = stage.defaults(ctx) if ctx is not None else {}
        out += [
            f"## `{stage.name}`",
            "",
            stage.summary,
            "",
            "| parameter | type | default | description |",
            "|---|---|---|---|",
        ]
        for f in P.fields(stage.Params):
            if f.name in dynamic:
                default = "*all, from config.toml*"
            elif P.has_static_default(f):
                d = P.static_default(f)
                default = "*from config*" if d is None else f"`{toml_value(d)}`"
            else:
                default = "**required**"
            kind = P.describe(hints[f.name]) + (" (**grid**)" if P.is_grid(f) else "")
            out.append(f"| `{f.name}` | {cell(kind)} | {cell(default)} | {cell(P.help_text(f))} |")
        out.append("")
    return "\n".join(out)
