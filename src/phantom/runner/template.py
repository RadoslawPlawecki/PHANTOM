"""
Run-file templates (``phantom new <stage>``) and stage descriptions
(``phantom stages <stage>``), both generated from the stage's ``Params`` so
they can never drift from what the stage actually accepts.
"""

from __future__ import annotations

from typing import Any

import tomlkit

from phantom.runner import parameters
from phantom.runner.stage import RunContext, Stage


def toml_value(value: Any) -> str:
    if isinstance(value, dict):
        table = tomlkit.inline_table()
        table.update(value)
        return table.as_string()
    return tomlkit.item(value).as_string()


def _placeholder(expected_type: Any) -> str:
    choices = parameters.literal_choices(expected_type)
    if choices:
        return toml_value(choices[0])
    return '""'


def _field_lines(stage: Stage, context: RunContext | None) -> list[tuple[str, str]]:
    """(``key = value`` line, trailing comment) per parameter."""
    hints = parameters.type_hints(stage.Params)
    dynamic = stage.defaults(context) if context is not None else {}
    available = stage.choices(context) if context is not None else {}
    lines = []
    for f in parameters.fields(stage.Params):
        expected_type = hints[f.name]
        notes = []
        if f.name in dynamic:
            line = f"{f.name} = {toml_value(dynamic[f.name])}"
        elif not parameters.has_static_default(f):
            options = available.get(f.name)
            line = (
                f"{f.name} = {toml_value(options[-1]) if options else _placeholder(expected_type)}"
            )
            notes.append("REQUIRED")
            if options:
                notes.append("available: " + " | ".join(str(o) for o in options))
        elif parameters.static_default(f) is None:
            # Optional with a config-derived default: shown commented out.
            line = f"# {f.name} = {_placeholder(expected_type)}"
        else:
            line = f"{f.name} = {toml_value(parameters.static_default(f))}"
        choices = parameters.literal_choices(expected_type)
        if choices:
            notes.append(" | ".join(str(c) for c in choices))
        if parameters.is_grid(f):
            notes.append("a list runs one job per value")
        if parameters.help_text(f):
            notes.append(parameters.help_text(f))
        lines.append((line, "; ".join(notes)))
    return lines


def render_template(stage: Stage, context: RunContext | None = None) -> str:
    output = [
        f"# Generated by: phantom new {stage.name}",
        f"# {stage.summary}",
        "# Fill in REQUIRED values, then: phantom validate <this file> && phantom run <this file>",
        "",
        "[run]",
        f'name = "{stage.name.replace(".", "_")}"',
        "",
        "[[steps]]",
        f'stage = "{stage.name}"',
    ]
    lines = _field_lines(stage, context)
    width = max((len(line) for line, _ in lines), default=0)
    for line, note in lines:
        output.append(f"{line.ljust(width)}  # {note}" if note else line)
    return "\n".join(output) + "\n"


def describe_stage(stage: Stage, context: RunContext | None = None) -> str:
    hints = parameters.type_hints(stage.Params)
    dynamic = stage.defaults(context) if context is not None else {}
    available = stage.choices(context) if context is not None else {}
    output = [f"{stage.name} -- {stage.summary}", "", "Parameters:"]
    for f in parameters.fields(stage.Params):
        if f.name in dynamic:
            default = f"default: {toml_value(dynamic[f.name])} (from config.toml)"
        elif parameters.has_static_default(f):
            d = parameters.static_default(f)
            default = (
                "default: use the config.toml location"
                if d is None
                else f"default: {toml_value(d)}"
            )
        else:
            default = "REQUIRED"
        grid = ", list = one job per value" if parameters.is_grid(f) else ""
        output.append(f"  {f.name}: {parameters.describe(hints[f.name])}{grid}  [{default}]")
        if parameters.help_text(f):
            output.append(f"      {parameters.help_text(f)}")
        if f.name in available:
            output.append("      available: " + ", ".join(str(o) for o in available[f.name]))
    return "\n".join(output)


def stages_markdown(stages: list[Stage], context: RunContext | None = None) -> str:
    """Every stage and its parameters as one Markdown page (the wiki's Stages page)."""
    output = [
        "# Stages",
        "",
        "Generated by `phantom stages --markdown` from the code -- do not edit by hand.",
        "Parameters marked **grid** accept a list: one job per value.",
        "",
    ]

    def cell(text: str) -> str:
        return text.replace("|", "\\|")

    for stage in sorted(stages, key=lambda s: s.name):
        hints = parameters.type_hints(stage.Params)
        dynamic = stage.defaults(context) if context is not None else {}
        output += [f"## `{stage.name}`", "", stage.summary, ""]
        if not parameters.fields(stage.Params):
            output += ["No parameters: everything comes from the configuration.", ""]
            continue
        output += ["| parameter | type | default | description |", "|---|---|---|---|"]
        for f in parameters.fields(stage.Params):
            if f.name in dynamic:
                default = "*all, from config.toml*"
            elif parameters.has_static_default(f):
                d = parameters.static_default(f)
                default = "*from config*" if d is None else f"`{toml_value(d)}`"
            else:
                default = "**required**"
            kind = parameters.describe(hints[f.name]) + (
                " (**grid**)" if parameters.is_grid(f) else ""
            )
            output.append(
                f"| `{f.name}` | {cell(kind)} | {cell(default)} | {cell(parameters.help_text(f))} |"
            )
        output.append("")
    return "\n".join(output)
